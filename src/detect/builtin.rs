pub fn builtin_rules() -> Vec<RuleSpec> {
    BUILTINS
        .iter()
        .map(|rule| RuleSpec {
            name: rule.name.to_owned(),
            kind: rule.kind,
            pattern: rule.pattern.to_owned(),
            markers: rule.markers.iter().map(|m| (*m).to_owned()).collect(),
            contains: rule.contains.iter().map(|c| (*c).to_owned()).collect(),
            category: rule.category,
            safety: rule.safety,
            ecosystem: rule.ecosystem.to_owned(),
        })
        .collect()
}
